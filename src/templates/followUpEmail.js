function escapeHtml(value = "") {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function getCopy(lang) {
  return COPY[lang] || COPY.en;
}

export function buildFollowUpEmail({ name, lang = "en", detectedRisk = "", appUrl = "" } = {}) {
  const copy = getCopy(lang);
  const safeName = String(name || "").trim() || "there";
  const focus = String(detectedRisk || "personalized report").trim();
  const targetUrl = String(appUrl || "https://neuromap-kids.webflow.io").replace(/\/+$/, "");

  const actionItems = copy.actions
    .map((item) => `<li style="margin:0 0 8px 0;">${escapeHtml(item)}</li>`)
    .join("");

  const html = `
    <div style="font-family:Arial,sans-serif;color:#172033;line-height:1.6;max-width:640px;margin:0 auto;padding:24px;">
      <div style="border:1px solid #d7eef9;border-radius:18px;padding:24px;background:#ffffff;">
        <p style="margin:0 0 8px 0;color:#1197d5;font-weight:800;letter-spacing:.08em;text-transform:uppercase;">NeuroMap Kids</p>
        <h1 style="margin:0 0 14px 0;font-size:26px;line-height:1.2;color:#102033;">${escapeHtml(copy.title)}</h1>
        <p style="margin:0 0 16px 0;">Hi ${escapeHtml(safeName)},</p>
        <p style="margin:0 0 16px 0;">${escapeHtml(copy.intro)}</p>
        <div style="background:#f1faff;border-left:5px solid #ff7a00;border-radius:12px;padding:14px 16px;margin:18px 0;">
          <strong>${escapeHtml(copy.focus)}</strong> ${escapeHtml(focus)}
        </div>
        <h2 style="font-size:18px;margin:20px 0 10px 0;color:#102033;">${escapeHtml(copy.actionTitle)}</h2>
        <ul style="padding-left:20px;margin:0 0 18px 0;">${actionItems}</ul>
        <p style="margin:0 0 20px 0;color:#52677e;">${escapeHtml(copy.note)}</p>
        <a href="${escapeHtml(targetUrl)}" style="display:inline-block;background:#1197d5;color:#fff;text-decoration:none;font-weight:800;border-radius:10px;padding:12px 18px;">${escapeHtml(copy.cta)}</a>
      </div>
    </div>
  `;

  const text = [
    copy.title,
    "",
    `Hi ${safeName},`,
    copy.intro,
    "",
    `${copy.focus} ${focus}`,
    "",
    copy.actionTitle,
    ...copy.actions.map((item) => `- ${item}`),
    "",
    copy.note,
    targetUrl
  ].join("\n");

  return {
    subject: copy.subject,
    html,
    text
  };
}
